function normalize(text) {
  return text.replace(/\s+/g, " ").trim();
}

const dictionary = Object.fromEntries(Object.entries({ ...questionText, ...assessmentText, ...translations }).map(([key, value]) => [normalize(key), value]));

// Display-only translation: API values, form answers and user-entered text stay intact.
export function t(text) {
  if (typeof text !== "string") return text;
  const key = normalize(text);
  if (dictionary[key]) return dictionary[key];
  const standard = key.match(/^Norme de performance (\d+)(.*)$/);
  if (standard) return `Performance Standard ${standard[1]}${standard[2] ? ` — ${t(standard[2].replace(/^\s*—\s*/, ""))}` : ""}`;
  const block = key.match(/^Bloc (\d+)(?: — (.+))?$/);
  if (block) return `Block ${block[1]}${block[2] ? ` — ${t(block[2])}` : ""}`;
  // Section summaries can contain several sentences after aggregation.
  if (key.includes(". ")) return key.split(/(?<=\.)\s+/).map((sentence) => dictionary[sentence] || sentence).join(" ");
  return text;
}
